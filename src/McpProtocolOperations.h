std::string BuildMcpDiscoveryBaseUrl(const AgentConfig & config) {
    const std::string host = (config.listen_host.empty() || config.listen_host == "0.0.0.0")
        ? "127.0.0.1"
        : config.listen_host;
    return "http://" + host + ":" + std::to_string(config.listen_port);
}

