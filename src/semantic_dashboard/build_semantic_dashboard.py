def write_dashboard(output_dir: Path, data: Dict[str, Any]) -> None:
    dashboard = output_dir / "dashboard"
    dashboard.mkdir(parents=True, exist_ok=True)
    (dashboard / "index.html").write_text(HTML, encoding="utf-8")
    js = "window.SEMANTIC_DASHBOARD_DATA = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
    (dashboard / "dashboard_data.js").write_text(js, encoding="utf-8")
    (output_dir / "dashboard_data.json").write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


def build(input_dir: Path, output_dir: Path) -> Dict[str, Any]:
    reset_output(output_dir)
    manifest = copy_objects(input_dir, output_dir)
    db_path = output_dir / "semantic_monitor.db"
    conn = connect_db(db_path)
    try:
        conn.executescript(SCHEMA)
        rel_to_doc = insert_documents(conn, input_dir, output_dir, manifest)
        insert_nodes_and_edges(conn, input_dir, rel_to_doc)
        insert_artifacts(conn, input_dir)
        insert_rounds(conn, input_dir)
        insert_markdown_derived(conn, input_dir, rel_to_doc)
        conn.commit()
        export_sql(conn, output_dir / "semantic_monitor.sql")
        data = build_dashboard_data(conn, input_dir)
    finally:
        conn.close()
    write_dashboard(output_dir, data)
    return {
        "db_path": str(db_path),
        "dashboard_path": str(output_dir / "dashboard" / "index.html"),
        "object_count": len(manifest),
        "output_dir": str(output_dir),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Build SQLite + local dashboard from semantic_monitor artifacts.")
    parser.add_argument("--input", required=True, help="Path to semantic_monitor directory")
    parser.add_argument("--output", required=True, help="Output directory for SQLite/object/dashboard bundle")
    args = parser.parse_args()
    input_dir = Path(args.input).resolve()
    output_dir = Path(args.output).resolve()
    if not input_dir.exists():
        raise SystemExit(f"input directory does not exist: {input_dir}")
    result = build(input_dir, output_dir)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
