TEXT_EXTENSIONS = {".md", ".txt", ".dot"}
JSON_EXTENSIONS = {".json"}


def now_iso() -> str:
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8-sig", errors="replace")


def read_json(path: Path) -> Any:
    try:
        return json.loads(read_text(path))
    except Exception:
        return None


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_text(text: str) -> str:
    return sha256_bytes(text.encode("utf-8", errors="replace"))


def slugify(value: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9_.-]+", "_", value).strip("_")
    return slug or "item"


def first_non_empty(*values: Any) -> str:
    for value in values:
        if value is None:
            continue
        text = str(value).strip()
        if text:
            return text
    return ""


def normalize_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def classify_document(rel_path: str) -> str:
    path = rel_path.replace("\\", "/").lower()
    if path.startswith("trace_cards/"):
        return "trace_card"
    if path.startswith("lenses/"):
        return "lens"
    if path.startswith("increment/"):
        return "increment"
    if "risk_queue" in path:
        return "risk_queue"
    if "gap_queue" in path:
        return "gap_queue"
    if "issues" in path:
        return "issues"
    if path.endswith(".json"):
        return "json"
    if path.endswith(".dot"):
        return "graph_dot"
    if path.endswith(".md"):
        return "markdown"
    return "object"


def markdown_title(text: str, fallback: str) -> str:
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            return stripped.lstrip("#").strip() or fallback
    return fallback


def infer_judgment(text: str) -> str:
    lower = text.lower()
    if "partial" in lower or "⚠" in text:
        return "partial"
    if "aligned" in lower or "✅" in text:
        return "aligned"
    if "missing" in lower:
        return "missing"
    if "suspicious" in lower:
        return "suspicious"
    return "unknown"


def infer_risk_level(text: str) -> str:
    lower = text.lower()
    if "critical" in lower or "严重" in lower:
        return "critical"
    if "high" in lower or "高" in lower:
        return "high"
    if "medium" in lower or "partial" in lower or "中" in lower:
        return "medium"
    if "low" in lower or "低" in lower:
        return "low"
    return "unknown"


def extract_round_refs(text: str) -> Tuple[str, str]:
    lower = text.lower()
    introduced = ""
    touched = ""
    intro_match = re.search(r"round\s*([0-9]+)\s*(?:引入|introduced)?", lower)
    if intro_match:
        introduced = "round_" + intro_match.group(1)
    touched_matches = re.findall(r"round\s*([0-9]+)", lower)
    if touched_matches:
        touched = "round_" + touched_matches[-1]
    return introduced, touched


def connect_db(db_path: Path) -> sqlite3.Connection:
    conn = sqlite3.connect(str(db_path))
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


