def reset_output(output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    for child in ["dashboard", "objects"]:
        path = output_dir / child
        if path.exists():
            shutil.rmtree(path)
        path.mkdir(parents=True, exist_ok=True)
    for filename in ["semantic_monitor.db", "semantic_monitor.sql", "object_manifest.json", "dashboard_data.json"]:
        path = output_dir / filename
        if path.exists():
            path.unlink()


def copy_objects(input_dir: Path, output_dir: Path) -> List[Dict[str, Any]]:
    objects_dir = output_dir / "objects"
    manifest: List[Dict[str, Any]] = []
    for path in sorted(input_dir.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(input_dir).as_posix()
        data = path.read_bytes()
        digest = sha256_bytes(data)
        object_name = f"{digest[:16]}_{slugify(rel)}"
        object_path = objects_dir / object_name
        object_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, object_path)
        manifest.append({
            "document_id": digest[:16],
            "rel_path": rel,
            "object_path": object_path.relative_to(output_dir).as_posix(),
            "kind": classify_document(rel),
            "size_bytes": len(data),
            "sha256": digest,
            "title": path.stem,
        })
    (output_dir / "object_manifest.json").write_text(
        json.dumps({"objects": manifest}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return manifest


def insert_documents(conn: sqlite3.Connection, input_dir: Path, output_dir: Path, manifest: List[Dict[str, Any]]) -> Dict[str, str]:
    rel_to_doc: Dict[str, str] = {}
    for item in manifest:
        rel = item["rel_path"]
        path = input_dir / rel
        content = ""
        title = item["title"]
        if path.suffix.lower() in TEXT_EXTENSIONS or path.suffix.lower() in JSON_EXTENSIONS:
            content = read_text(path)
            if path.suffix.lower() == ".md":
                title = markdown_title(content, path.stem)
        conn.execute(
            """
            INSERT INTO documents(document_id, rel_path, object_path, kind, size_bytes, sha256, title, content, created_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                item["document_id"],
                rel,
                item["object_path"],
                item["kind"],
                item["size_bytes"],
                item["sha256"],
                title,
                content,
                now_iso(),
            ),
        )
        rel_to_doc[rel] = item["document_id"]
    return rel_to_doc


def load_semantic_network(input_dir: Path) -> Dict[str, Any]:
    data = read_json(input_dir / "semantic_network.json")
    return data if isinstance(data, dict) else {}


def load_navigation_tree(input_dir: Path) -> Dict[str, Any]:
    data = read_json(input_dir / "navigation_tree.json")
    return data if isinstance(data, dict) else {}


def insert_nodes_and_edges(conn: sqlite3.Connection, input_dir: Path, rel_to_doc: Dict[str, str]) -> None:
    semantic = load_semantic_network(input_dir)
    navigation = load_navigation_tree(input_dir)
    source_doc = rel_to_doc.get("semantic_network.json", "")

    nodes: Dict[str, Dict[str, Any]] = {}
    for node in semantic.get("key_nodes", []) or []:
        node_id = node.get("node_id")
        if node_id:
            nodes[node_id] = dict(node)
    nav_root = navigation.get("navigation_tree", {})
    for node in nav_root.get("high_value_nodes", []) or []:
        node_id = node.get("node_id")
        if node_id:
            merged = nodes.get(node_id, {})
            merged.update(node)
            nodes[node_id] = merged

    layer_dist = nav_root.get("layer_distribution", {})
    for layer, info in layer_dist.items():
        if isinstance(info, dict) and info.get("node_id"):
            node_id = str(info.get("node_id"))
            nodes.setdefault(node_id, {
                "node_id": node_id,
                "layer": layer,
                "semantic_name": first_non_empty(info.get("summary"), layer),
                "child_count": info.get("children_count", info.get("count", 0)),
            })
        if isinstance(info, dict) and isinstance(info.get("children"), dict):
            for key, child in info["children"].items():
                node_id = child.get("node_id")
                if node_id:
                    nodes.setdefault(node_id, {
                        "node_id": node_id,
                        "layer": layer,
                        "semantic_name": key,
                        "parent_id": info.get("parent"),
                        "child_count": child.get("children_count", 0),
                        "raw_json": child,
                    })

    for node_id, node in sorted(nodes.items()):
        conn.execute(
            """
            INSERT OR REPLACE INTO nodes(node_id, layer, semantic_name, parent_id, child_count, evidence_type, risk_level, round_id, source_document_id, raw_json)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                node_id,
                first_non_empty(node.get("layer"), infer_layer(node_id)),
                first_non_empty(node.get("semantic_name"), node.get("summary"), node_id),
                node.get("parent_id") or node.get("parent"),
                int_or_zero(node.get("child_count", node.get("children_count", 0))),
                node.get("evidence_type") or node.get("evidence_strength"),
                infer_risk_level(normalize_json(node)),
                infer_round_from_node(node_id),
                source_doc,
                normalize_json(node),
            ),
        )

    edge_types = (semantic.get("edges_summary", {}) or {}).get("types", {}) or {}
    edge_index = 0
    for relation, count in edge_types.items():
        edge_index += 1
        conn.execute(
            "INSERT OR REPLACE INTO edges(edge_id, relation_type, raw_json) VALUES (?, ?, ?)",
            (f"summary_edge_{edge_index}", relation, normalize_json({"count": count})),
        )


def infer_layer(node_id: str) -> str:
    for layer in ["L1_META", "L2_DOMAIN", "L3_FLOW", "L4_ATOM", "L5_RAW"]:
        if node_id.startswith(layer):
            return layer
    return ""


def infer_round_from_node(node_id: str) -> str:
    match = re.search(r"frag_([0-9]+)", node_id)
    if not match:
        return ""
    number = int(match.group(1))
    if number <= 1021:
        return "round_1"
    if number <= 1023:
        return "round_2"
    if number <= 1025:
        return "round_3"
    return "round_4"


def int_or_zero(value: Any) -> int:
    try:
        return int(value)
    except Exception:
        return 0


def insert_artifacts(conn: sqlite3.Connection, input_dir: Path) -> None:
    artifacts = read_json(input_dir / "artifacts_index.json")
    if not isinstance(artifacts, dict):
        return
    for artifact_id, item in sorted(artifacts.items()):
        if not isinstance(item, dict):
            continue
        conn.execute(
            """
            INSERT OR REPLACE INTO artifacts(artifact_id, artifact_path, artifact_type, source_file, status, node_count, edge_count, fragment_count, description, raw_json)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                artifact_id,
                item.get("path"),
                item.get("type"),
                item.get("source_file"),
                item.get("status"),
                int_or_zero(item.get("node_count")),
                int_or_zero(item.get("edge_count")),
                int_or_zero(item.get("fragments", item.get("fragment_count"))),
                item.get("description"),
                normalize_json(item),
            ),
        )


def insert_rounds(conn: sqlite3.Connection, input_dir: Path) -> None:
    ledger = read_json(input_dir / "increment" / "increment_ledger.json")
    if not isinstance(ledger, dict):
        return
    root = ledger.get("increment_ledger", ledger)
    for item in root.get("rounds", []) or []:
        if not isinstance(item, dict):
            continue
        round_index = int_or_zero(item.get("round_id", item.get("round_index")))
        round_id = f"round_{round_index}" if round_index else slugify(str(item.get("round_type", "round")))
        delta_nodes = item.get("delta_nodes") or {}
        total_delta_nodes = int_or_zero(delta_nodes.get("total_added")) if isinstance(delta_nodes, dict) else 0
        conn.execute(
            """
            INSERT OR REPLACE INTO rounds(round_id, round_index, round_type, input_source, base_artifact, output_summary,
              added_fragment_count, skipped_duplicate_fragment_count, delta_fragment_count, delta_node_count, risk_count, raw_json)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                round_id,
                round_index,
                item.get("round_type"),
                normalize_json(item.get("input_source", {})),
                item.get("base_artifact"),
                item.get("output_summary"),
                int_or_zero(item.get("added_fragment_count")),
                int_or_zero(item.get("skipped_duplicate_fragment_count")),
                int_or_zero(item.get("delta_fragments", item.get("added_fragment_count"))),
                total_delta_nodes,
                int_or_zero(item.get("risk_count")),
                normalize_json(item),
            ),
        )


def insert_markdown_derived(conn: sqlite3.Connection, input_dir: Path, rel_to_doc: Dict[str, str]) -> None:
    for rel, doc_id in rel_to_doc.items():
        path = input_dir / rel
        if path.suffix.lower() != ".md":
            continue
        content = read_text(path)
        title = markdown_title(content, Path(rel).stem)
        normalized = rel.replace("\\", "/")
        if normalized.startswith("trace_cards/"):
            card_id = Path(rel).stem
            introduced, touched = extract_round_refs(content)
            conn.execute(
                """
                INSERT OR REPLACE INTO trace_cards(card_id, document_id, title, judgment, risk_level, introduced_round, last_touched_round, content)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (card_id, doc_id, title, infer_judgment(content), infer_risk_level(content), introduced, touched, content),
            )
        elif normalized.startswith("lenses/"):
            lens_id = Path(rel).stem
            conn.execute(
                """
                INSERT OR REPLACE INTO lenses(lens_id, document_id, title, lens_type, content)
                VALUES (?, ?, ?, ?, ?)
                """,
                (lens_id, doc_id, title, lens_id.replace("_lens", ""), content),
            )
        elif normalized in {"issues.md", "risk_queue.md", "gap_queue.md"}:
            issue_id = Path(rel).stem
            conn.execute(
                """
                INSERT OR REPLACE INTO issues(issue_id, document_id, title, severity, status, content)
                VALUES (?, ?, ?, ?, ?, ?)
                """,
                (issue_id, doc_id, title, infer_risk_level(content), "open", content),
            )


def export_sql(conn: sqlite3.Connection, output_path: Path) -> None:
    output_path.write_text("\n".join(conn.iterdump()), encoding="utf-8")


def query_all(conn: sqlite3.Connection, sql: str) -> List[Dict[str, Any]]:
    conn.row_factory = sqlite3.Row
    rows = conn.execute(sql).fetchall()
    return [dict(row) for row in rows]


def build_dashboard_data(conn: sqlite3.Connection, input_dir: Path) -> Dict[str, Any]:
    semantic = load_semantic_network(input_dir)
    navigation = load_navigation_tree(input_dir)
    return {
        "generated_at": now_iso(),
        "summary": {
            "total_nodes": int_or_zero((semantic.get("nodes_summary", {}) or {}).get("total")),
            "total_edges": int_or_zero((semantic.get("edges_summary", {}) or {}).get("total")),
            "layers": semantic.get("layers", {}),
            "latest_artifact": ((read_json(input_dir / "increment" / "increment_ledger.json") or {}).get("increment_ledger", {}) or {}).get("latest_artifact", ""),
        },
        "navigation": navigation.get("navigation_tree", navigation),
        "nodes": query_all(conn, "SELECT * FROM nodes ORDER BY layer, node_id LIMIT 5000"),
        "rounds": query_all(conn, "SELECT * FROM rounds ORDER BY round_index"),
        "artifacts": query_all(conn, "SELECT * FROM artifacts ORDER BY artifact_id"),
        "trace_cards": query_all(conn, "SELECT * FROM trace_cards ORDER BY judgment, card_id"),
        "issues": query_all(conn, "SELECT * FROM issues ORDER BY severity DESC, issue_id"),
        "lenses": query_all(conn, "SELECT lens_id, title, lens_type, content FROM lenses ORDER BY lens_id"),
        "documents": query_all(conn, "SELECT document_id, rel_path, object_path, kind, size_bytes, title FROM documents ORDER BY kind, rel_path"),
    }


