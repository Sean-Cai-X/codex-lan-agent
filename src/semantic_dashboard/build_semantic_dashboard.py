"""
Build a local semantic monitor dashboard from semantic_monitor artifacts.

Inputs:
  semantic_monitor/ with markdown/json/dot files generated by MCP analysis.

Outputs:
  semantic_monitor_dashboard_sqlite/
    semantic_monitor.db
    semantic_monitor.sql
    objects/
    object_manifest.json
    dashboard/index.html
    dashboard/dashboard_data.js

The dashboard is intentionally static and dependency-free. SQLite stores the
queryable review index; copied file objects preserve source evidence.
"""

